import numpy as np

# ИСХОДНЫЕ ДАННЫЕ

order_id = np.arange(2001, 2013)
Region = np.array([
    "Бишкек", "Ош", "Бишкек", "Каракол", "Ош", "Токмок",
    "Бишкек", "Ош", "Каракол", "Токмок", "Бишкек", "Ош"
])
quantity = np.array([2, 1, 5, 3, 2, 8, 1, 4, 2, 3, 6, 1])
unit_price = np.array([1500, 20000, 800, 5000, 1200, 700, 25000, 3000, 4500, 2000, 900, 18000])
discount = np.array([0.05, 0.10, 0.00, 0.15, 0.05, 0.20, 0.30, 0.10, 0.00, 0.05, 0.50, 0.10])
unit_cost = np.array([1000, 16000, 600, 4000, 900, 500, 18000, 2200, 3500, 1500, 800, 14000])

# Базовые финансовые расчеты (векторизованно)
revenue = quantity * unit_price * (1 - discount)
profit = revenue - quantity * unit_cost

print("--- БАЗОВЫЕ РАСЧЕТЫ ---")
print("Выручка (revenue):", revenue)
print("Прибыль (profit):", profit)
print()

# ЗАДАНИЕ 1. Первичный отбор

print("=== ЗАДАНИЕ 1: Первичный отбор ===")
# 1. Выручка выше порога (например, > 10000)
high_revenue_mask = revenue > 10000
# 2. Количество не менее трех единиц (quantity >= 3)
min_qty_mask = quantity >= 3
# 3. Заказы из конкретного региона (например, "Бишкек")
bishkek_mask = (Region == "Бишкек")

print("Маска по выручке (>10000):", high_revenue_mask)
print("Маска по количеству (>=3):", min_qty_mask)
print("Маска по региону (Бишкек):", bishkek_mask)
print()

# ЗАДАНИЕ 2. Составные условия

print("=== ЗАДАНИЕ 2: Составные условия ===")
# Условия: скидка >= 20% (0.20), доход > 10000, количество >= 4.
# Требуется одновременное выполнение любых двух условий из трех.
cond_discount = discount >= 0.20
cond_revenue = revenue > 10000
cond_quantity = quantity >= 4

# Считаем количество выполненных условий для каждого заказа (через приведение к int)
conditions_count = cond_discount.astype(int) + cond_revenue.astype(int) + cond_quantity.astype(int)
complex_mask = conditions_count >= 2

print("Заказы, выполняющие как минимум 2 составных критерия:", order_id[complex_mask])
print("Обоснование: Такой подход позволяет находить нетривиальные заказы (например, с большой скидкой и высокой выручкой одновременно) с помощью гибкой логической фильтрации.\n")

# ЗАДАНИЕ 3. Поиск убыточных заказов

print("=== ЗАДАНИЕ 3: Поиск убыточных заказов ===")
loss_mask = profit < 0
loss_orders = order_id[loss_mask]
loss_share = loss_mask.sum() / order_id.size * 100

print(f"Убыточные заказы (ID): {loss_orders}")
print(f"Доля убыточных заказов среди всех: {loss_share:.2f}%")
print("Объяснение: Высокая выручка сама по себе не гарантирует прибыль, так как себестоимость единицы (unit_cost) может быть слишком близка к цене продажи или превышать ее, а агрессивные скидки могут полностью «съедать» маржинальность товара.\n")

# ЗАДАНИЕ 4. Анализ скидок

print("=== ЗАДАНИЕ 4: Анализ скидок ===")
# Заказы, сочетающие большую скидку (>= 20%) с низкой или отрицательной прибылью (profit <= 0)
high_discount_low_profit = (discount >= 0.20) & (profit <= 0)
print("Заказы с высокой скидкой и нулевой/отрицательной прибылью:", order_id[high_discount_low_profit])
print("Важно: Сама по себе большая скидка не является единственной причиной убытка — он может быть вызван высокой закупочной ценой или браком в данных. Корреляционный анализ требует осторожности.\n")

# ЗАДАНИЕ 5. Выявление подозрительных явлений

print("=== ЗАДАНИЕ 5: Выявление подозрительных явлений ===")
# Правило подозрительности: скидка >= 30% И отрицательная или нулевая прибыль
suspicious_mask = (discount >= 0.30) & (profit <= 0)
print("Подозрительные заказы, требующие проверки:", order_id[suspicious_mask])
print("Объяснение: Заказы с огромными скидками, уходящие в минус, могут быть системным сбоем, ошибкой оператора или проявлением мошенничества. Стандартные акции (например, скидка 5-10%) объясняются бизнес-логикой маркетинга.\n")

# ЗАДАНИЕ 6. Анализ сегментов

print("=== ЗАДАНИЕ 6: Анализ сегментов ===")
reg1, reg2 = "Бишкек", "Ош"
mask_reg1 = (Region == reg1)
mask_reg2 = (Region == reg2)

print(f"Регион: {reg1}")
print(f"  - Количество заказов: {mask_reg1.sum()}")
print(f"  - Общая выручка: {revenue[mask_reg1].sum():.2f}")
print(f"  - Убыточных заказов: {(profit[mask_reg1] < 0).sum()}")

print(f"Регион: {reg2}")
print(f"  - Количество заказов: {mask_reg2.sum()}")
print(f"  - Общая выручка: {revenue[mask_reg2].sum():.2f}")
print(f"  - Убыточных заказов: {(profit[mask_reg2] < 0).sum()}")
print()

# ЗАДАНИЕ 7. Исследование аномалий
print("=== ЗАДАНИЕ 7: Исследование аномалий ===")
mean_revenue_before = revenue.mean()
clean_revenue = revenue[~suspicious_mask]
mean_revenue_after = clean_revenue.mean()

print(f"Средний доход до исключения аномалий: {mean_revenue_before:.2f}")
print(f"Средний доход после исключения аномалий: {mean_revenue_after:.2f}")
print("Объяснение: Метрики сильно зависят от выбранного правила фильтрации. Удалять аномалии «вслепую» нельзя — сначала нужно подтвердить причину их появления с помощью бизнес-проверок.\n")

