print("=== ДОПОЛНИТЕЛЬНОЕ ЗАДАНИЕ: Сравнение правил фильтрации ===")
rule_1 = discount > 0.40  
rule_2 = (discount > 0.10) & (profit < 1000)  #

print(f"Количество заказов по Правилу 1 (скидка > 40%): {rule_1.sum()}")
print(f"Количество заказов по Правилу 2 (скидка > 10% и прибыль < 1000): {rule_2.sum()}")
print("Вывод: Правило 1 отлично подходит для первичного отгрузочного контроля явных аномалий, а Правило 2 слишком широкое и генерирует много ложных срабатываний, захватывая стандартные низкомаржинальные товары.")