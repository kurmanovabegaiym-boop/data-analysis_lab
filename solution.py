# ДОПОЛНИТЕЛЬНОЕ ЗАДАНИЕ. Универсальная функция проверки

print("=== ДОПОЛНИТЕЛЬНОЕ ЗАДАНИЕ: Универсальная функция проверки ===")

def check_numeric_array(arr):
    """
    Универсальная функция проверки числового массива с использованием векторизованных операций NumPy.
    Возвращает словарь с ключевыми характеристиками качества данных.
    """
    report = {
        "shape": arr.shape,
        "dtype": arr.dtype,
        "missing_count": int(np.isnan(arr).sum()) if np.issubdtype(arr.dtype, np.inexact) else 0,
        "infinite_count": int(np.isinf(arr).sum()) if np.issubdtype(arr.dtype, np.inexact) else 0,
        "negative_count": int((arr < 0).sum()) if np.issubdtype(arr.dtype, np.number) else 0
    }
    return report

# Тестируем функцию на массиве цен
price_check_result = check_numeric_array(unit_price)
print("Результат проверки массива unit_price:", price_check_result)