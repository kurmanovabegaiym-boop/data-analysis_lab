import numpy as np

# ИСХОДНЫЕ ДАННЫЕ

order_id = np.array([1001, 1002, 1003, 1004, 1005, 1006])
quantity = np.array([2, 3, 0, 5, -1, 4])
unit_price = np.array([1500, 2000, 1200, 3000, 2500, np.nan])
discount = np.array([0.10, 0.05, 0.00, 0.15, 0.10, 0.20])

# ЗАДАНИЕ 1. Проверка структуры массивов

print("=== ЗАДАНИЕ 1: Структура массивов ===")
for name, arr in [('order_id', order_id), ('quantity', quantity), ('unit_price', unit_price), ('discount', discount)]:
    print(f"Массив '{name}':")
    print(f"  - Размер (size): {arr.size}")
    print(f"  - Форма (shape): {arr.shape}")
    print(f"  - Измерения (ndim): {arr.ndim}")
    print(f"  - Тип данных (dtype): {arr.dtype}")
print("\nПроверка безопасности доступа по индексам: Все массивы имеют одномерную форму (1D) и одинаковую длину, что позволяет безопасно сопоставлять элементы по единому индексу до проведения фильтрации.\n")

# ЗАДАНИЕ 2. Контроль качества (Булевы маски)

print("=== ЗАДАНИЕ 2: Контроль качества ===")
invalid_quantity = (quantity <= 0)
missing_price = np.isnan(unit_price)
invalid_discount = (discount < 0) | (discount > 1)
bad_orders = invalid_quantity | missing_price | invalid_discount

print(f"Заказы с нулевым/отрицательным количеством: {invalid_quantity}")
print(f"Цены с пропущенными значениями (NaN): {missing_price}")
print(f"Скидки вне диапазона [0, 1]: {invalid_discount}")
print(f"Общая маска проблемных (бракованных) заказов: {bad_orders}\n")

# ЗАДАНИЕ 3. Формирование рабочего набора

print("=== ЗАДАНИЕ 3: Формирование рабочего набора ===")
valid_quantity = quantity > 0
valid_price = np.isfinite(unit_price) & (unit_price >= 0)
valid_discount = (discount >= 0) & (discount <= 1)

valid_orders_mask = valid_quantity & valid_price & valid_discount

# Очищенные массивы
clean_order_id = order_id[valid_orders_mask]
clean_quantity = quantity[valid_orders_mask]
clean_unit_price = unit_price[valid_orders_mask]
clean_discount = discount[valid_orders_mask]

print(f"Маска действительных заказов: {valid_orders_mask}")
print(f"Очищенные ID заказов: {clean_order_id}")
print(f"Очищенное количество: {clean_quantity}")
print(f"Очищенные цены: {clean_unit_price}")
print("\nОбъяснение: Нельзя фильтровать каждый массив независимо, так как при разной длине масок нарушится индексное соответствие. Заказ из одного массива окажется привязан к чужой цене или скидке из другого, что разрушит целостность финансовых расчетов.\n")


# ЗАДАНИЕ 4. Подготовка матрицы

print("=== ЗАДАНИЕ 4: Подготовка матрицы ===")
order_matrix = np.column_stack((clean_quantity, clean_unit_price, clean_discount))
print(f"Форма матрицы действительных заказов (shape): {order_matrix.shape}")
print("Матрица (строки — заказы, столбцы — [количество, цена, скидка]):")
print(order_matrix)
print("\nОбъяснение: Выбран формат с объединением колонок (column_stack), так как он группирует однородные признаки в столбцы, а отдельные наблюдения (заказы) размещает по строкам, что является стандартом для математического анализа в NumPy.\n")

# ЗАДАНИЕ 5. Преобразование данных (reshape)

print("=== ЗАДАНИЕ 5: Преобразование данных (reshape) ===")
sales_24 = np.arange(1, 25)
matrix_4x6 = sales_24.reshape(4, 6)
matrix_6x4 = sales_24.reshape(6, 4)

print("Матрица 4 × 6 (Строки — недели, Столбцы — категории):")
print(matrix_4x6)
print("\nМатрица 6 × 4 (Строки — категории, Столбцы — недели):")
print(matrix_6x4)
print("\nОбъяснение: При изменении формы через reshape общее количество элементов неизменно (24), но смысл меняется кардинально. В варианте 4x6 мы анализируем общие продажи по неделям (каждая строка — неделя), а в варианте 6x4 — динамику конкретной товарной категории во времени (каждая строка — категория).\n")

# ЗАДАНИЕ 6. Проверка источников

print("=== ЗАДАНИЕ 6: Проверка источников ===")
corrupted_unit_price = np.array([1500, 2000, 1200, 3000, 2500]) # Имитация потери записи
is_length_match = (order_id.size == corrupted_unit_price.size)
print(f"Длина order_id: {order_id.size}, Длина цен: {corrupted_unit_price.size}")
print(f"Согласованы ли длины массивов? {is_length_match}")
print("\nОбъяснение: Одинаковое количество элементов в разных файлах еще не гарантирует правильность. Если в одном файле строка продублировалась, а в другом пропала, общая длина совпадет, но данные окажутся сдвинутыми. Обязательна проверка уникальности ключей (order_id) и целостности связей.\n")



# ЗАДАНИЕ 7. Подготовка к аналитике

print("=== ЗАДАНИЕ 7: Подготовка к аналитике (Матрица продаж) ===")
