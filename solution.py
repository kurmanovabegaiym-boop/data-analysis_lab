import numpy as np

order_id = np.arange(2001, 2013)
region = np.array([
    "Бишкек", "Ош", "Бишкек", "Каракол", "Ош", "Токмок",
    "Бишкек", "Ош", "Каракол", "Токмок", "Бишкек", "Ош"
])
quantity = np.array([2, 1, 5, 3, 2, 8, 1, 4, 2, 3, 6, 1])
unit_price = np.array([1500, 20000, 800, 5000, 1200, 700, 25000, 3000, 4500, 2000, 900, 18000])
discount = np.array([0.05, 0.10, 0.00, 0.15, 0.05, 0.20, 0.30, 0.10, 0.00, 0.05, 0.50, 0.10])
unit_cost = np.array([1000, 16000, 600, 4000, 900, 500, 18000, 2200, 3500, 1500, 800, 14000])

revenue = quantity * unit_price * (1 - discount)
profit = revenue - quantity * unit_cost

print("--- Расчет базовых показателей ---")
print("Выручка по заказам:", revenue)
print("Прибыль по заказам:", profit)
print("\n" + "="*50 + "\n")


print("--- Задание 1: Простые фильтры ---")


mask_revenue = revenue > 10000
mask_qty = quantity >= 3
mask_region = (region == "Бишкек")

print("1. Заказы с выручкой больше 10 тыс.:", order_id[mask_revenue])
print("2. Заказы, где взяли от 3 штук:", order_id[mask_qty])
print("3. Заказы только из Бишкека:", order_id[mask_region])
print("\n" + "="*50 + "\n")



print("--- Задание 2: Фильтр по двум условиям из трех ---")

cond1 = discount >= 0.20
cond2 = revenue > 10000
cond3 = quantity >= 4

conditions_met = cond1.astype(int) + cond2.astype(int) + cond3.astype(int)
mask_complex = conditions_met >= 2

print("Заказы, подошедшие хотя бы по двум критериям:", order_id[mask_complex])
print("Пояснение: Выбрал логику 2 из 3, чтобы поймать крупные или выигрышные заказы, даже если они чуть не дотягивают по одному из параметров.")
print("\n" + "="*50 + "\n")



print("--- Задание 3: Минусовые заказы ---")

loss_mask = profit < 0
loss_orders = order_id[loss_mask]
loss_percentage = (loss_mask.sum() / len(order_id)) * 100

print("Убыточные заказы (ID):", loss_orders)
print(f"Процент убыточных заказов: {loss_percentage:.1f}%")
print("Вывод: Большая выручка не гарантирует плюс. Если закупочная цена высока или мы дали слишком большую скидку, заказ уйдет в минус.")
print("\n" + "="*50 + "\n")


print("--- Задание 4: Скидки и прибыльность ---")

high_disc_low_profit = (discount >= 0.20) & (profit <= 0)
print("Заказы со скидкой от 20%, ушедшие в ноль или минус:", order_id[high_disc_low_profit])
print("Вывод: Нельзя сказать, что во всем виноваты только скидки. Возможно, у этих товаров изначально была завышенная себестоимость.")
print("\n" + "="*50 + "\n")


print("--- Задание 5: Проверка на странности ---")

suspicious_mask = (discount >= 0.30) & (profit <= 0)
print("Заказы, похожие на ошибку или фрод:", order_id[suspicious_mask])
print("Пояснение: Скидки в 5-10% — это нормальная практика. А вот скидка 50%, загоняющая чек в минус, требует проверки менеджеров.")
print("\n" + "="*50 + "\n")


print("--- Задание 6: Сравнение Бишкека и Оша ---")

mask_bishkek = region == "Бишкек"
mask_osh = region == "Ош"

print("Бишкек:")
print(" - Всего заказов:", mask_bishkek.sum())
print(f" - Выручка: {revenue[mask_bishkek].sum():.0f}")
print(" - Из них убыточных:", (profit[mask_bishkek] < 0).sum())

print("\nОш:")
print(" - Всего заказов:", mask_osh.sum())
print(f" - Выручка: {revenue[mask_osh].sum():.0f}")
print(" - Из них убыточных:", (profit[mask_osh] < 0).sum())
print("\n" + "="*50 + "\n")

# Задание 7. Влияние аномалий на среднее

print("--- Задание 7: Средняя выручка до и после очистки ---")

avg_before = revenue.mean()
avg_after = revenue[~suspicious_mask].mean()

print(f"Средняя выручка (все данные): {avg_before:.2f}")
print(f"Средняя выручка (без аномальных): {avg_after:.2f}")
print("Вывод: Если просто удалять подозрительные строчки, средние цифры сильно меняются. Сначала надо точно узнать причину аномалии.")
print("\n" + "="*50 + "\n")

